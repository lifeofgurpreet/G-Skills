#!/usr/bin/env python3
"""Check/render the native Beads task graph; br is not a user runtime dependency."""
from pathlib import Path
import argparse
import json
import re
import sys

ROOT=Path(__file__).resolve().parents[1]

def load(root=ROOT):
    rows=[json.loads(line) for line in (root/'.beads/issues.jsonl').read_text().splitlines() if line.strip()]
    ids={row['id']:row for row in rows}
    if len(ids)!=len(rows):raise ValueError('duplicate task IDs')
    for row in rows:
        if not re.fullmatch(r'gs-[a-z0-9]+(?:\.\d+)?',row['id']):raise ValueError('invalid task ID')
        if row['status'] not in ('open','in_progress','blocked','deferred','closed'):raise ValueError('invalid task state')
        if not row.get('description') or not row.get('acceptance_criteria'):raise ValueError('task needs description and executable acceptance boundary')
        if row['status']=='closed' and not row.get('close_reason'):raise ValueError('closed task needs a source/outcome receipt')
        for dep in row.get('dependencies',[]):
            if dep['depends_on_id'] not in ids:raise ValueError('missing graph dependency')
            if row['status']=='closed' and dep['type']=='blocks' and ids[dep['depends_on_id']]['status']!='closed':raise ValueError('closed work depends on unfinished prerequisite')
    def walk(key,active,complete):
        if key in active:raise ValueError('cyclic dependency graph')
        if key in complete:return
        active.add(key)
        for dep in ids[key].get('dependencies',[]):
            if dep['type'] in ('blocks','parent-child'):walk(dep['depends_on_id'],active,complete)
        active.remove(key);complete.add(key)
    done=set()
    for key in ids:walk(key,set(),done)
    return sorted(rows,key=lambda r:(r['issue_type']!='epic',r['priority'],r['id'].split('.')[0],int(r['id'].split('.')[-1]) if '.' in r['id'] else 0))


def render(rows):
    ids={r['id']:r for r in rows}
    lines=['# Roadmap: the agent does the work','',
           'Canonical state: `.beads/issues.jsonl`. This file is generated by `python3 tools/roadmap.py --write`; CI checks it for drift and graph errors.',
           '','The human provides a goal, approved targets and required consent. The terminal agent owns routine discovery, scaffolding, verification, collection and handoff. A skill is not OAuth access, a running daemon or authorization for external changes.',
           '','## Task graph','', '| Task | State | Priority | Blocking prerequisites |','|---|---|---:|---|']
    for row in rows:
        deps=[d['depends_on_id'] for d in row.get('dependencies',[]) if d['type']=='blocks']
        lines.append(f"| `{row['id']}` {row['title'].replace('|','/')} | {row['status']} | {row['priority']} | {', '.join('`'+d+'`' for d in deps) or '—'} |")
    lines+=['','```mermaid','flowchart LR']
    for row in rows:
        if row['issue_type']=='epic':continue
        name=row['id'].replace('-','_').replace('.','_');lines.append(f'  {name}["{row["id"]}: {row["status"]}"]')
        for dep in row.get('dependencies',[]):
            if dep['type']=='blocks':lines.append('  '+dep['depends_on_id'].replace('-','_').replace('.','_')+' --> '+name)
    lines+=['```','','## What counts as done','']
    for row in rows:
        lines += [f"### {row['id']} — {row['title']}",'',row['description'],'','**Acceptance:** '+row['acceptance_criteria'],'']
        if row.get('close_reason'):lines+=['**Receipt:** '+row['close_reason'],'']
    lines+=['## How another agent continues','',
            'Read `AGENTS.md`, this roadmap and the owning skill. Use `br ready --json` when Beads is installed, or inspect the versioned graph directly. Keep task status and acceptance evidence distinct. Update with native `br` commands, export the JSONL, regenerate this file and run validation. Never ship a Beads database, local skill library or customer workspace.',
            '', 'Public-source maintenance uses this repository graph. A user monitoring their own host does not need Beads or a GitHub account to run the installed skill. Their private runtime state and handoff belong inside their own workspace, not this graph.','']
    return '\n'.join(lines)


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--write',action='store_true');parser.add_argument('--check',action='store_true');args=parser.parse_args(argv)
    try:
        rows=load();text=render(rows);path=ROOT/'ROADMAP.md'
        if args.write:path.write_text(text)
        elif not path.exists() or path.read_text()!=text:raise ValueError('ROADMAP.md is missing/stale; regenerate with --write')
        print(f'PASS: {len(rows)} native task records; dependencies and roadmap match')
        return 0
    except (OSError,ValueError,KeyError) as exc:
        print(f'FAIL: roadmap: {exc}',file=sys.stderr);return 1

if __name__=='__main__':raise SystemExit(main())
